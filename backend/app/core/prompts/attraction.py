"""从行程里提取景点的提示词（供地图节点使用）。"""


def build_attraction_prompt(plan_text: str) -> str:
    return f"""
    你是一个专业的旅行规划助手。请从以下行程中提取出所有**值得参观的景点/地标/公园/博物馆**。

    ## 行程信息
    {plan_text}

    ## 提取规则
    1. **只提取景点**：如公园、广场、博物馆、海滩、山、寺、塔、古城、步行街等
    2. **只认原文**：景点名必须是行程里原样出现过的地名。禁止推断、补充，
       绝对不要因为"这天没写具体地点"就自己挑一条街凑数——
       地图上多出一个没去过的地方，比少一个更糟。
    3. **没有就跳过**：某一天全是餐饮、住宿、自由活动、返程这类没有具体地名的安排，
       就不要给那天输出任何景点（那天照常显示"没有需要标注的景点"）。
    4. **去重**：同一个景点只提取一次，不要跨天重复计数
    5. **别名**：如果景点有别名，使用标准名称
    6. **上限**：每天最多 6 个，挑最能代表当天的
    7. **city 必填**：填这个景点所在的城市名（地级市，例如"济南""泰安"，不要带"省"字）。
       从行程上下文推断——"抵达济南"、"乘车前往泰安"、"曲阜东站"这类描述都指明了城市。
       实在推断不出来就留空字符串，**不要**拿省会或第一天落地的城市去填。
       这个字段直接决定地图上取哪个坐标：漏了或填错，"玉皇顶"会被匹配到临沂那座同名山。

    ## 返回格式
    返回 JSON 数组，包含景点名称、所在城市和它出现的天数：
    {{
        "attractions": [
            {{"name": "星海广场", "day": 1, "city": "大连"}},
            {{"name": "老虎滩海洋公园", "day": 1, "city": "大连"}},
            {{"name": "泰山风景区", "day": 2, "city": "泰安"}},
            {{"name": "孔庙", "day": 3, "city": "曲阜"}}
        ]
    }}

    **只返回 JSON，不要返回其他内容。**
    """
